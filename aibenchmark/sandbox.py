import subprocess
import sys
import os
import textwrap
import tempfile
import re


SANDBOX_TIMEOUT = 10

# ---------------------------------------------------------------------------
# What this sandbox does, and what it does NOT do (read before trusting it)
#
# What it does:
#   * Runs model code in a fresh temporary directory, with a 10-second timeout.
#   * Passes a minimal environment to the subprocess: PATH (and, on Windows,
#     SYSTEMROOT / TEMP / APPDATA / USERPROFILE) only. No API keys, no proxy
#     variables, so model code cannot read secrets from os.environ.
#   * Deliberately does NOT set PYTHONNOUSERSITE=1, and adds pytest's own
#     site-packages directory to PYTHONPATH (see _sandbox_env). A 2026-10-24
#     regression proved why: with PYTHONNOUSERSITE=1 and APPDATA dropped,
#     a Windows per-user pytest install was invisible to the subprocess,
#     which failed with "No module named pytest" and scored every single
#     evaluation in run 10 as execution_error / no_tests_ran.
#   * Installs a sitecustomize.py in the temporary directory that blocks
#     Python-level network access (socket.connect / create_connection /
#     getaddrinfo / gethostbyname raise OSError). Ordinary model code that
#     tries `import requests`, `urllib`, or `socket` therefore fails fast
#     instead of reaching the network.
#
# What it does NOT do (honest limit, not a bug to paper over):
#   * This is NOT an OS-level security boundary. Model code runs as the same
#     OS user, so deliberately malicious code could still read files outside
#     the temporary directory, or shell out to an external tool such as curl
#     (the socket patch only covers Python code in the pytest process).
#   * If you need protection against deliberately malicious code, the next
#     step is a real container / VM (e.g. Docker with --network=none), not
#     a bigger Python patch. For the project's stated purpose -- scoring
#     ordinary model output -- the measures above close the gaps that were
#     actually present: leaked secrets in the environment and unrestricted
#     Python network access.
# ---------------------------------------------------------------------------

_SITECUSTOMIZE = '''\
# Auto-generated by aibenchmark.sandbox. Blocks Python-level network access
# for code run inside the benchmark sandbox. See sandbox.py for limits.
import socket


def _blocked(*args, **kwargs):
    raise OSError("network access is blocked in the benchmark sandbox")


def _blocked_ex(*args, **kwargs):
    # connect_ex() normally returns an errno, not an exception.
    return 101  # ENETUNREACH


socket.socket.connect = _blocked
socket.socket.connect_ex = _blocked_ex
socket.create_connection = _blocked
socket.getaddrinfo = _blocked
socket.gethostbyname = _blocked
socket.gethostbyname_ex = _blocked
'''


def extract_code(response: str) -> str:
    # First try standard markdown code blocks
    pattern = r"```(?:\w+)?\n(.*?)```"
    matches = re.findall(pattern, response, re.DOTALL)
    if matches:
        code = matches[-1].strip()
        # Check if it's a tool call JSON and extract the code field
        if code.startswith('{') and '"code"' in code:
            try:
                import json
                parsed = json.loads(code)
                if 'arguments' in parsed and 'code' in parsed['arguments']:
                    return parsed['arguments']['code']
                if 'code' in parsed:
                    return parsed['code']
            except:
                pass
        return code

    # Try to extract from tool call JSON format (e.g., qwen2.5-coder-tools)
    tool_call_pattern = r'"code"\s*:\s*"((?:\\.|[^"\\])*)"'
    matches = re.findall(tool_call_pattern, response)
    if matches:
        # Unescape the code
        code = matches[-1].replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')
        return code.strip()

    # Fallback: return response as-is
    return response.strip()


def _pytest_site_dir():
    """Directory holding pytest (its site-packages parent), or None.

    Needed because the sandbox subprocess gets a minimal environment: on
    Windows, dropping APPDATA alone can hide a per-user pytest install
    from Python's site module, even without PYTHONNOUSERSITE set.
    """
    try:
        import pytest

        return os.path.dirname(os.path.dirname(os.path.abspath(pytest.__file__)))
    except Exception:
        return None


def _sandbox_env(tmpdir: str, extra_dirs=()) -> dict:
    """Minimal environment for the sandboxed subprocess.

    Deliberately drops every *_API_KEY / *_TOKEN / proxy variable that a
    normal os.environ.copy() would have leaked to model code.

    It does NOT block user site-packages (no PYTHONNOUSERSITE=1) and it
    passes APPDATA / USERPROFILE through on Windows: pytest is commonly
    installed per-user on Windows, and blocking that path made the
    subprocess report "No module named pytest" and fail every evaluation
    (run 10, 2026-10-24). Blocking user site buys no real security here
    anyway -- this sandbox is not an OS-level boundary, see the header --
    while breaking the scorer entirely is a fatal cost.
    """
    env = {}
    if "PATH" in os.environ:
        env["PATH"] = os.environ["PATH"]
    if os.name == "nt":
        for key in (
            "SYSTEMROOT",
            "SYSTEMDRIVE",
            "TEMP",
            "TMP",
            "APPDATA",
            "USERPROFILE",
            "LOCALAPPDATA",
        ):
            if key in os.environ:
                env[key] = os.environ[key]
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    # sitecustomize.py lives in tmpdir (and, for mutant tests, solution_dir);
    # PYTHONPATH makes sure Python finds it at interpreter startup.
    # pytest's site-packages dir is appended as well, so the subprocess
    # finds pytest even when the minimal environment hides user site.
    dirs = [tmpdir] + list(extra_dirs)
    site_dir = _pytest_site_dir()
    if site_dir and site_dir not in dirs:
        dirs.append(site_dir)
    env["PYTHONPATH"] = os.pathsep.join(dirs)
    return env


def _write_sitecustomize(directory: str) -> None:
    with open(os.path.join(directory, "sitecustomize.py"), "w") as f:
        f.write(_SITECUSTOMIZE)


# Matches one pytest -v result line, e.g. "test_x.py::test_y PASSED [100%]".
# Group 1 is the WHOLE node id (file + class + test + parameters),
# captured greedily: the line must END with the status (plus an
# optional reason in parentheses, padding, and an optional "[ xx%]"
# bracket — real pytest -v pads the status column and annotates
# skips, e.g. "SKIPPED (unconditional skip)   [100%]"), and that end
# anchor is what lets a greedy id match disambiguate a status-like
# word inside a parameter (e.g. test_v[hello world]) from the real
# trailing status. This replaces the old ::\S+ matcher, which
# silently dropped any result line whose parametrized id contained
# whitespace.
# Requiring "::" in the id avoids counting a test's own printed
# output that happens to contain the word PASSED / FAILED on its own.
_RESULT_LINE = re.compile(
    r"^(.*::.*) (PASSED|FAILED|ERROR|SKIPPED|XFAIL|XPASS)"
    r"( \([^)]*\))?\s*(\[.*\])?\s*$"
)


def _parse_pytest_output(output: str):
    """Return (passed, failed, errors, skipped, tests) from pytest -v
    output. tests is the ordered list of {"name": full node id,
    "status": lowercase outcome} for every matched result line, in
    output order. XFAIL / XPASS are included in tests but NOT counted
    in passed/failed/errors/skipped: they are expected-failure
    markers, not ordinary passes. ONE matcher serves both counts and
    identities, so the two can never disagree: tallies over tests
    (excluding xfail/xpass) always equal the counts."""
    passed = failed = errors = skipped = 0
    tests = []
    for line in output.splitlines():
        m = _RESULT_LINE.match(line.strip())
        if not m:
            continue
        name, status = m.group(1), m.group(2)
        tests.append({"name": name, "status": status.lower()})
        if status == "PASSED":
            passed += 1
        elif status == "FAILED":
            failed += 1
        elif status == "ERROR":
            errors += 1
        elif status == "SKIPPED":
            skipped += 1
        # XFAIL / XPASS: listed, not counted (see docstring).
    return passed, failed, errors, skipped, tests


def _run_pytest(cwd: str, test_arg: str, tmpdir: str, extra_dirs=()):
    """Run pytest once. Returns (returncode, output, passed, failed,
    errors, skipped, tests). Step 2 threads skipped through (previously
    parsed but discarded) so evidence capture can report it; per-test
    capture threads the ordered (node id, outcome) list through the
    same way. Scores, statuses and error types are computed exactly
    as before; the list is observation only, never a scoring input.

    Raises subprocess.TimeoutExpired on timeout, so callers can decide
    whether a timeout counts as a kill (mutants) or a timeout (direct tests).
    """
    result = subprocess.run(
        [sys.executable, "-m", "pytest", test_arg, "-v", "--tb=short",
         "--no-header", "-p", "no:cacheprovider"],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=SANDBOX_TIMEOUT,
        env=_sandbox_env(tmpdir, extra_dirs),
    )
    output = result.stdout + result.stderr
    passed, failed, errors, skipped, tests = _parse_pytest_output(output)
    return result.returncode, output, passed, failed, errors, skipped, tests


def _counts_evidence(passed, failed, errors, skipped):
    """Evidence counts from one pytest run. collected is the number of
    items that produced a result line (passed + failed + errors +
    skipped). Skipped items are counted here but excluded from the
    score denominator, exactly as the scoring code already does."""
    return {
        "passed": passed,
        "failed": failed,
        "skipped": skipped,
        "errors": errors,
        "collected": passed + failed + errors + skipped,
    }


def _none_evidence():
    """Evidence when nothing was measured (run killed, file missing,
    harness error): None, never zero. Zero would claim a measurement."""
    return {
        "passed": None,
        "failed": None,
        "skipped": None,
        "errors": None,
        "collected": None,
    }


def _run_tests_impl(
    problem_dir: str,
    solution_code: str,
    test_file_path: str,
):
    """Shared implementation. Returns (score, status, error_type,
    evidence). Score, status and error_type are computed EXACTLY as the
    pre-step-2 run_tests_sandboxed did; evidence is observed alongside
    from the same single pytest run, never a second run. Evidence
    carries the step-2 counts plus "tests": the ordered per-test
    (node id, outcome) list, or None when nothing was measured
    (missing file, timeout, harness error)."""
    # problem_dir is kept for API compatibility with existing callers; the
    # test file is copied into the temporary directory, so it is not used.
    if not os.path.exists(test_file_path):
        return 0.0, "error", "test_file_missing", {**_none_evidence(),
                                                    "tests": None}
    solution_code = textwrap.dedent(solution_code)
    with tempfile.TemporaryDirectory() as tmpdir:
        solution_path = os.path.join(tmpdir, "solution.py")
        test_dest = os.path.join(tmpdir, "test_solution.py")
        with open(solution_path, "w") as f:
            f.write(solution_code)
        with open(test_dest, "w") as f:
            with open(test_file_path) as src:
                f.write(src.read())
        _write_sitecustomize(tmpdir)
        try:
            returncode, output, passed, failed, errors, skipped, tests = _run_pytest(
                tmpdir, "test_solution.py", tmpdir
            )
            total = passed + failed + errors
            evidence = {**_counts_evidence(passed, failed, errors, skipped),
                        "tests": tests}
            if total == 0:
                if returncode == 5 or "no tests ran" in output.lower():
                    return 0.0, "error", "no_tests_ran", evidence
                return 0.0, "error", "execution_error", evidence
            score = passed / total
            if failed == 0 and errors == 0:
                status = "passed"
            elif passed > 0:
                status = "partial"
            else:
                status = "failed"
            return score, status, None, evidence
        except subprocess.TimeoutExpired:
            return 0.0, "timeout", "sandbox_timeout", {**_none_evidence(),
                                                        "tests": None}
        except Exception as e:
            return 0.0, "error", f"error: {type(e).__name__}", {**_none_evidence(),
                                                                  "tests": None}


def run_tests_sandboxed(
    problem_dir: str,
    solution_code: str,
    test_file_path: str,
) -> tuple[float, str, str]:
    """Pre-step-2 interface, preserved exactly. Scores, statuses and
    error types are unchanged; evidence is dropped here."""
    score, status, error_type, _evidence = _run_tests_impl(
        problem_dir, solution_code, test_file_path
    )
    return score, status, error_type


def run_tests_sandboxed_with_evidence(
    problem_dir: str,
    solution_code: str,
    test_file_path: str,
):
    """Step 2 interface. Same single pytest run as run_tests_sandboxed,
    plus the evidence counts and per-test list observed from it."""
    return _run_tests_impl(problem_dir, solution_code, test_file_path)


def _mutant_evidence(gate_outcome, gate_counts, kills, total, outcomes,
                     tests=None):
    """Testing evidence. Gate awareness is structural: when the gate
    fails (or never runs), kills is None and every mutant is
    "not_run" -- never zero. Zero kills is only reported when the gate
    passed and mutants actually ran. "tests" is the gate run's ordered
    per-test (node id, outcome) list, or None when the gate never ran
    (provider-side failure, timeout, harness error, no mutants). The
    gate list is what explains a gate failure; mutant runs keep
    outcomes only, never per-test lists."""
    return {
        "gate_outcome": gate_outcome,
        "gate": gate_counts,
        "mutants_killed": kills,
        "mutants_total": total,
        "mutants": outcomes,
        "tests": tests,
    }


def _run_mutants_impl(
    problem_dir: str,
    test_code: str,
    reference_implementation: str,
    mutants: dict,
):
    """Shared implementation. Returns (score, error_type, evidence).
    Score and error_type are computed EXACTLY as the pre-step-2
    run_mutant_tests_sandboxed did; evidence is observed alongside
    from the same pytest runs, never extra runs."""
    # problem_dir is kept for API compatibility; see run_tests_sandboxed.
    test_code = textwrap.dedent(test_code)
    reference_implementation = textwrap.dedent(reference_implementation)
    total_mutants = len(mutants)
    if total_mutants == 0:
        return 0.0, "no_mutants", _mutant_evidence(
            "not_run", _none_evidence(), None, 0, {}
        )
    mutants_killed = 0
    outcomes = {}
    with tempfile.TemporaryDirectory() as tmpdir:
        test_dest = os.path.join(tmpdir, "test_generated.py")
        with open(test_dest, "w") as f:
            f.write(test_code)
        solution_dir = os.path.join(tmpdir, "solution_dir")
        os.makedirs(solution_dir)
        solution_path = os.path.join(solution_dir, "solution.py")
        with open(solution_path, "w") as f:
            f.write(reference_implementation)
        _write_sitecustomize(tmpdir)
        _write_sitecustomize(solution_dir)
        # --- Reference gate (strict) ---
        # The generated tests must pass CLEANLY against the reference:
        # returncode 0, at least one test, no failures, no errors. Anything
        # else means the test suite itself is broken, and scoring mutants
        # against it would be meaningless -- in particular, a suite that
        # errors on import must NOT go on to "kill" every mutant.
        try:
            returncode, output, passed, failed, errors, skipped, tests = _run_pytest(
                solution_dir, "../test_generated.py", tmpdir,
                extra_dirs=(solution_dir,),
            )
        except subprocess.TimeoutExpired:
            return 0.0, "sandbox_timeout", _mutant_evidence(
                "not_run", _none_evidence(), None, total_mutants,
                {mid: "not_run" for mid in mutants},
            )
        except Exception as e:
            return 0.0, f"error: {type(e).__name__}: {e}", _mutant_evidence(
                "not_run", _none_evidence(), None, total_mutants,
                {mid: "not_run" for mid in mutants},
            )
        total_ref = passed + failed + errors
        gate_counts = _counts_evidence(passed, failed, errors, skipped)
        if total_ref == 0:
            return 0.0, "no_tests_ran", _mutant_evidence(
                "not_run", gate_counts, None, total_mutants,
                {mid: "not_run" for mid in mutants},
                tests,
            )
        if returncode != 0 or failed > 0 or errors > 0:
            return 0.0, "reference_impl_failed", _mutant_evidence(
                "failed", gate_counts, None, total_mutants,
                {mid: "not_run" for mid in mutants},
                tests,
            )
        # --- Mutant loop ---
        for mutant_id, mutant_data in mutants.items():
            try:
                mutant_code = textwrap.dedent(mutant_data["code"])
            except Exception:
                # Malformed mutant entry: do not count it as killed.
                outcomes[mutant_id] = "not_run"
                continue
            with open(solution_path, "w") as f:
                f.write(mutant_code)
            try:
                # Mutant-run per-test lists are deliberately NOT retained:
                # only the kill/survive outcome is evidence. The gate
                # run's list (captured above) is what explains a score.
                returncode, output, passed, failed, errors, skipped, _tests = _run_pytest(
                    solution_dir, "../test_generated.py", tmpdir,
                    extra_dirs=(solution_dir,),
                )
            except subprocess.TimeoutExpired:
                # A mutant that hangs is detected by the timeout: killed.
                mutants_killed += 1
                outcomes[mutant_id] = "killed"
                continue
            except Exception:
                # Our own harness error, not a test failure: do not inflate.
                outcomes[mutant_id] = "not_run"
                continue
            total = passed + failed + errors
            if total == 0:
                # No tests ran against this mutant: cannot tell, not killed.
                outcomes[mutant_id] = "not_run"
                continue
            if returncode != 0 or failed > 0 or errors > 0:
                mutants_killed += 1
                outcomes[mutant_id] = "killed"
            else:
                outcomes[mutant_id] = "survived"
    score = mutants_killed / total_mutants if total_mutants > 0 else 0.0
    return score, None, _mutant_evidence(
        "passed", gate_counts, mutants_killed, total_mutants, outcomes,
        tests,
    )


def run_mutant_tests_sandboxed(
    problem_dir: str,
    test_code: str,
    reference_implementation: str,
    mutants: dict,
) -> tuple[float, str | None]:
    """Pre-step-2 interface, preserved exactly. Score and error type
    are unchanged; evidence is dropped here."""
    score, error_type, _evidence = _run_mutants_impl(
        problem_dir, test_code, reference_implementation, mutants
    )
    return score, error_type


def run_mutant_tests_sandboxed_with_evidence(
    problem_dir: str,
    test_code: str,
    reference_implementation: str,
    mutants: dict,
):
    """Step 2 interface. Same pytest runs as
    run_mutant_tests_sandboxed, plus the evidence observed from them
    (counts, gate-run per-test list, mutant outcomes)."""
    return _run_mutants_impl(
        problem_dir, test_code, reference_implementation, mutants
    )
